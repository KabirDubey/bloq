#!/usr/bin/env python3
"""Read the gate schedule of a Low et al. (arXiv:2605.30455) gate-sequence figure from its vector data.

Input: the XML of `mutool trace <figure>.pdf`, for a figure drawn by stim's timeslice style with one panel
per tick (Fig. 5(c)/(d): 3 panels per row, panel pitch 468.016 pt; Fig. 48: 4 per row, 654.7 x 505.35 pt).
Output (JSON on stdout): per tick, the resets and measurements with their basis and the two-qubit gates as
[kind, control, target] with kind "CX" or "CXSWAP", in figure grid units (origin 60 pt, pitch 33.941 pt,
y down). How the marks are read:
  - a CX or CXSWAP is a 3.75 pt black line; its target end sits on an 18 pt white disc;
  - a CXSWAP target also carries a black 3 pt cross (stim's XSWAP mark); its control a white cross;
  - R/M labels are 22.5 pt (or 19.5 pt) DejaVu Sans Mono glyphs, followed by a 12 pt "X" for the X basis.
Usage: fig_trace.py trace.xml --cols 4 --px 654.7 --py 505.35 [--rust NAME]
With --rust NAME it prints a Rust constant instead, with coordinates shifted by (-2, -1) into the low-gadgets
generator's frame (data at (2i, 2j+1), slots at (2a+1, 2b)).
"""
import argparse, collections, json, sys
import xml.etree.ElementTree as ET

UNIT, ORIGIN = 33.941, 60.0


def pt(c):
    if c.tag == "curveto":
        return float(c.get("x3")), float(c.get("y3"))
    return float(c.get("x")), float(c.get("y"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("trace")
    ap.add_argument("--cols", type=int, required=True)
    ap.add_argument("--px", type=float, required=True)
    ap.add_argument("--py", type=float)
    ap.add_argument("--rust")
    a = ap.parse_args()
    py = a.py or a.px
    root = ET.parse(a.trace).getroot()

    def grid(x, y):
        c, r = int(x // a.px), int(y // py)
        gx, gy = (x - ORIGIN - a.px * c) / UNIT, (y - ORIGIN - py * r) / UNIT
        assert abs(gx - round(gx)) < 0.2 and abs(gy - round(gy)) < 0.2, (x, y)
        return a.cols * r + c, (round(gx), round(gy))

    lines, discs, crosses = [], [], []
    for el in root.iter():
        pts = [pt(c) for c in el if c.tag in ("moveto", "lineto", "curveto")]
        if not pts:
            continue
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        mid = ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2)
        if el.tag == "stroke_path" and el.get("linewidth") == "3.75":
            lines.append((pts[0], pts[-1]))
        elif el.tag == "stroke_path" and el.get("linewidth") == "3" and el.get("color") == "0 0 0":
            crosses.append(mid)
        elif el.tag == "fill_path" and el.get("color") == "1 1 1" and el.get("alpha") is None:
            if round(max(xs) - min(xs), 1) == 18.0:
                discs.append(mid)

    def dist(p, marks):
        return min((((p[0] - m[0]) ** 2 + (p[1] - m[1]) ** 2) ** 0.5 for m in marks), default=1e9)

    ticks = collections.defaultdict(lambda: {"resets": {}, "measures": {}, "gates": []})
    for p, q in lines:
        ctrl, targ = (p, q) if dist(q, discs) < dist(p, discs) else (q, p)
        assert dist(targ, discs) < 1.0, ("no target disc", targ)
        kind = "CXSWAP" if dist(targ, crosses) < 1.0 else "CX"
        tk, c = grid(*ctrl)
        _, t = grid(*targ)
        ticks[tk]["gates"].append([kind, c, t])
    spans = []
    for el in root.iter("span"):
        g = list(el)
        txt = "".join(x.get("unicode") or "" for x in g)
        spans.append((float(el.get("trm").split()[0]), txt, float(g[0].get("x")), float(g[0].get("y"))))
    for i, (size, txt, x, y) in enumerate(spans):
        if txt not in ("R", "M"):
            continue
        sub = spans[i + 1][1] if i + 1 < len(spans) and spans[i + 1][0] == 12 else ""
        tk, q = grid(x + 0.33 * size, y - 0.36 * size)
        kind = "resets" if txt == "R" else "measures"
        ticks[tk][kind][q] = "X" if sub.upper() == "X" else "Z"

    if not a.rust:
        out = {
            tk: {
                "resets": sorted([list(q), b] for q, b in v["resets"].items()),
                "measures": sorted([list(q), b] for q, b in v["measures"].items()),
                "gates": sorted(v["gates"]),
            }
            for tk, v in sorted(ticks.items())
        }
        json.dump(out, sys.stdout, indent=1)
        print()
        return
    s = lambda q: f"({q[0] - 2}, {q[1] - 1})"
    print(f"/// Generated by low_gadgets/tools/fig_trace.py from the d = 5 figure; frame (x - 2, y - 1).")
    print(f"pub const {a.rust}: &[Tick] = &[")
    for tk in range(max(ticks) + 1):
        v = ticks[tk]
        r = ", ".join(f"({s(q)}, '{b}')" for q, b in sorted(v["resets"].items()))
        m = ", ".join(f"({s(q)}, '{b}')" for q, b in sorted(v["measures"].items()))
        g = ", ".join(f"({str(k == 'CXSWAP').lower()}, {s(c)}, {s(t)})" for k, c, t in sorted(v["gates"]))
        print(f"    Tick {{ resets: &[{r}], measures: &[{m}], gates: &[{g}] }},")
    print("];")


if __name__ == "__main__":
    main()
